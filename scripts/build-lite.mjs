// Build data/lite.json and data/lite.mjs: everything the helper needs for the
// curated ingredients, in one small file a browser can load.
//
//   node scripts/build-lite.mjs
//
// Input is the JSON already in data/, so this needs no USDA download. Run it
// after any change to aliases.json, units.json or a data build. `npm test`
// fails when the committed lite files are out of date.
//
// What is kept: every alias, and for each USDA record an alias points at, the
// fields the helper reads (densities by form, count portions, composition).
// What is dropped: the 8,400 foods no alias names, the raw USDA portion rows
// behind each density, and the brand rows behind each label median. Those stay
// in ingredients.json and branded-gaps.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const DATA = new URL('../data/', import.meta.url);
const readData = (name) => JSON.parse(readFileSync(new URL(`${name}.json`, DATA), 'utf8'));

/** The parsed data files, keyed as createConverter names them. */
export function readSources() {
  return {
    units: readData('units'),
    aliases: readData('aliases'),
    ingredients: readData('ingredients'),
    dairyModel: readData('dairy-model'),
    brandedGaps: readData('branded-gaps'),
    eggSizes: readData('egg-sizes'),
    measurements: readData('measurements'),
  };
}

function trimRecord(record) {
  return {
    id: record.id,
    fdcId: record.fdcId,
    description: record.description,
    source: record.source,
    composition: record.composition,
    forms: record.forms.map((f) => ({
      form: f.form,
      densityGPerMl: f.densityGPerMl,
      ...(f.portionSpreadPct !== undefined ? { portionSpreadPct: f.portionSpreadPct } : {}),
      ...(f.waterEquivalent !== undefined ? { waterEquivalent: f.waterEquivalent } : {}),
    })),
    ...(record.counts ? { counts: record.counts } : {}),
  };
}

function trimGap(gap) {
  return {
    id: gap.id,
    label: gap.label,
    n: gap.n,
    medianDensityGPerMl: gap.medianDensityGPerMl,
    q1DensityGPerMl: gap.q1DensityGPerMl,
    q3DensityGPerMl: gap.q3DensityGPerMl,
    medianUncertaintyPct: gap.medianUncertaintyPct,
    warnings: gap.warnings,
  };
}

/** The lite data object, built from the parsed data files. */
export function buildLite({ units, aliases, ingredients, dairyModel, brandedGaps, eggSizes, measurements }) {
  const wantedRecords = new Set(aliases.aliases.filter((a) => a.fdcId !== undefined).map((a) => a.fdcId));
  const wantedGaps = new Set(aliases.aliases.filter((a) => a.branded).map((a) => a.branded));
  const records = ingredients.ingredients.filter((i) => wantedRecords.has(i.fdcId));
  const missing = [...wantedRecords].filter((id) => !records.some((r) => r.fdcId === id));
  if (missing.length) throw new Error(`aliases.json names fdcIds that ingredients.json lacks: ${missing.join(', ')}`);
  return {
    schemaVersion: 1,
    note: 'The curated ingredients of cooking-density in one file: every alias, the USDA records the aliases point at (densities, counts and composition; raw portion rows left out), label medians without their brand rows, units, the dairy model and egg sizes. Built by scripts/build-lite.mjs from the other files in data/, which remain the full record.',
    sources: [...ingredients.sources, { id: 'usda-branded', ...brandedGaps.source }],
    units: units.units,
    aliases: aliases.aliases,
    ingredients: records.map(trimRecord),
    dairyModel,
    brandedGaps: {
      source: brandedGaps.source,
      gaps: brandedGaps.gaps.filter((g) => wantedGaps.has(g.id)).map(trimGap),
    },
    eggSizes,
    measurements: measurements.measurements,
  };
}

/**
 * JSON text with one unit, alias, ingredient or gap per line: small enough to
 * ship, and a changed alias shows up as one changed line in a diff.
 */
export function serialise(lite) {
  const rows = (list) => `[\n${list.map((item) => JSON.stringify(item)).join(',\n')}\n]`;
  const parts = Object.entries(lite).map(([key, value]) => {
    if (Array.isArray(value) && value.every((v) => v && typeof v === 'object')) return `${JSON.stringify(key)}:${rows(value)}`;
    if (key === 'brandedGaps') return `"brandedGaps":{"source":${JSON.stringify(value.source)},"gaps":${rows(value.gaps)}}`;
    return `${JSON.stringify(key)}:${JSON.stringify(value)}`;
  });
  return `{\n${parts.join(',\n')}\n}\n`;
}

/** The same data as an ES module, for runtimes that cannot import JSON. */
export function serialiseModule(lite) {
  return `// Generated by scripts/build-lite.mjs from the JSON in data/. Do not edit.\nexport default ${serialise(lite).trimEnd()};\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const lite = buildLite(readSources());
  const json = serialise(lite);
  writeFileSync(new URL('lite.json', DATA), json);
  writeFileSync(new URL('lite.mjs', DATA), serialiseModule(lite));
  console.log(`data/lite.json: ${lite.aliases.length} aliases, ${lite.ingredients.length} USDA records, ${lite.brandedGaps.gaps.length} label medians, ${(json.length / 1024).toFixed(0)} KB`);
}
